export function useI18n() {
  const persisted = useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);
  const locale: Locale = persisted.locale;
  const dictionary = locale === "zh-Hant" ? zhHant : en;
  const t = (key: CopyKey) => dictionary[key];
  const setLocale = (next: Locale) => writePersisted({ locale: next });
  return { t, locale, setLocale };
}

export function messageForError(code: string | undefined, t: (key: CopyKey) => string, fallback?: string) {
  const map: Partial<Record<string, CopyKey>> = {
    invalid_url: "errInvalidUrl",
    unreachable: "errUnreachable",
    timeout: "errTimeout",
    not_dan: "errNotDan",
    bad_response: "errBadResponse",
    unauthorized: "errUnauthorized",
    sold_out: "tillSoldOut",
    unknown_item: "tillUnknown",
    reward_pending: "loyaltyFull",
    duplicate_number: "menuDuplicate",
    no_reward: "loyaltyLede",
    invalid: "errGeneric",
    forbidden: "errForbidden",
    locked: "errLocked",
    not_set_up: "errNotSetUp",
  };
  if (code && map[code]) return t(map[code]);
  return fallback || t("errGeneric");
}
